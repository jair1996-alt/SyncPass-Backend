-- SyncPass API - migracion opcional e idempotente
-- Tablas: proyectos y participantes
--
-- La aplicacion usa spring.jpa.hibernate.ddl-auto=update, por lo que Hibernate
-- puede crear/actualizar estas tablas al iniciar. Este script sirve para
-- aprovisionar o verificar el esquema manualmente sin borrar datos existentes.
--
-- No ejecutar automaticamente desde la aplicacion. Ejecutar con un usuario
-- administrador de PostgreSQL/Supabase y revisar el resultado antes de desplegar.

BEGIN;

CREATE TABLE IF NOT EXISTS proyectos (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    nombre VARCHAR(150) NOT NULL,
    descripcion TEXT,
    estado VARCHAR(20) NOT NULL
);

CREATE TABLE IF NOT EXISTS participantes (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    nombre VARCHAR(150) NOT NULL,
    email VARCHAR(254) NOT NULL,
    proyecto_id BIGINT NOT NULL
);

DO $$
BEGIN
    IF NOT EXISTS (
        SELECT 1
        FROM pg_constraint
        WHERE conname = 'fk_participantes_proyecto'
    ) THEN
        ALTER TABLE participantes
            ADD CONSTRAINT fk_participantes_proyecto
            FOREIGN KEY (proyecto_id) REFERENCES proyectos(id);
    END IF;

    IF NOT EXISTS (
        SELECT 1
        FROM pg_constraint
        WHERE conname = 'uk_participante_proyecto_email'
    ) THEN
        ALTER TABLE participantes
            ADD CONSTRAINT uk_participante_proyecto_email
            UNIQUE (proyecto_id, email);
    END IF;

    IF NOT EXISTS (
        SELECT 1
        FROM pg_constraint
        WHERE conname = 'ck_proyectos_estado'
    ) THEN
        ALTER TABLE proyectos
            ADD CONSTRAINT ck_proyectos_estado
            CHECK (estado IN ('ACTIVO', 'INACTIVO', 'FINALIZADO'));
    END IF;
END
$$;

CREATE INDEX IF NOT EXISTS idx_participantes_proyecto_id
    ON participantes (proyecto_id);

COMMIT;
